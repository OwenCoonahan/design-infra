export const bezier = (b: readonly number[]) => `cubic-bezier(${b.join(", ")})`

/**
 * CSS variables a theme ships for its motion language (on :root). Themes also map
 * `--ease-motion-{out,in,in-out}` in @theme so Tailwind generates `ease-motion-out` etc.; durations are
 * used as `duration-(--motion-fast)`.
 */
export function motionCssVars(lang: MotionLanguage) {
  const t = MOTION_TOKENS[lang]
  return {
    "motion-fast": `${t.fast}ms`,
    "motion-base": `${t.base}ms`,
    "motion-slow": `${t.slow}ms`,
    "motion-ease-out": bezier(t.easeOut),
    "motion-ease-in": bezier(t.easeIn),
    "motion-ease-in-out": bezier(t.easeInOut),
  }
}
export const MOTION_LANGUAGE_NAMES = Object.keys(MOTION_LANGUAGES) as MotionLanguage[]

