/**
 * catalog/toolchain.json → validated, ranked docs + the bootstrap bundle.
 *
 *   pnpm toolchain
 *
 * → catalog/TOOLCHAIN.md   ranked table + per-tool setup (agents read this)
 * → public/bootstrap.mjs   scripts/bootstrap.ts bundled with the toolchain inlined (served at /bootstrap.mjs)
 * → presets/components.registries.json   every registry step (single source of truth: the toolchain)
 */
import { execFileSync } from "node:child_process"
import { readFile, writeFile } from "node:fs/promises"

import { config, configureData, SITE_URL } from "../lib/config"
import { Tool } from "../lib/catalog/schema"

const TIER = { 1: "Foundation — always", 2: "Default libraries", 3: "Situational", 4: "Paid / metered / keyed" } as const

async function main() {
  const raw = JSON.parse(await readFile("catalog/toolchain.json", "utf8")) as { tools: unknown[] }
  const tools = configureData(raw).tools.map((t) => Tool.parse(t)).sort((a, b) => a.rank - b.rank)
  const ids = new Set<string>()
  const ranks = new Set<number>()
  for (const t of tools) {
    if (ids.has(t.id)) throw new Error(`duplicate tool id ${t.id}`)
    if (ranks.has(t.rank)) throw new Error(`duplicate rank ${t.rank} (${t.id})`)
    ids.add(t.id)
    ranks.add(t.rank)
  }

  const step = (s: Tool["setup"][number]) => {
    switch (s.kind) {
      case "registry":
        return `registry \`${s.namespace}\` → \`${s.url}\``
      case "npm":
        return `${s.dev ? "dev " : ""}package${s.packages.length > 1 ? "s" : ""} \`${s.packages.join(" ")}\``
      case "shadcn":
        return `\`npx shadcn@latest add ${s.items.join(" ")}\``
      case "mcp":
        return `project MCP \`${s.name}\` (.mcp.json)`
      case "mcp-user":
        return `user MCP \`${s.name}\`: \`${s.command}\``
      case "run":
        return `${s.interactive ? "manual" : "run"}: \`${s.command}\``
      case "agent-note":
        return `agent note`
    }
  }
  const md = [
    "<!-- GENERATED by scripts/build-toolchain.ts from catalog/toolchain.json -->",
    "# Toolchain — what to install, in what order",
    "",
    "The advanced bootstrap applies tiers 1–2 by default. Prefer --connect for first use; install only what you need.",
    "Keyed tools require explicit selection with --only or --tier 4 and authorized credentials:",
    "",
    "```bash",
    `curl -fsSL ${SITE_URL}/bootstrap.mjs -o /tmp/di.mjs && node /tmp/di.mjs --connect --client claude-code`,
    "node /tmp/di.mjs --list        # ranked list   ·   --tier 3   ·   --only motion,agentation   ·   --dry-run",
    "```",
    "",
    "| # | tool | tier | track | why it's here | secrets |",
    "|---|---|---|---|---|---|",
    ...tools.map(
      (t) =>
        `| ${t.rank} | ${t.docs ? `[${t.name}](${t.docs})` : t.name} | ${t.tier} | ${t.track} | ${t.why.replace(/\|/g, "\\|")} | ${t.secrets.map((s) => `\`${s.env}\``).join(", ") || "—"} |`
    ),
    "",
  ]
  for (const tier of [1, 2, 3, 4] as const) {
    md.push(`## Tier ${tier} — ${TIER[tier]}`, "")
    for (const t of tools.filter((x) => x.tier === tier)) {
      md.push(`### ${t.rank}. ${t.name}`, "", `${t.why} **Use:** ${t.use}`, "")
      for (const s of t.setup) md.push(`- ${step(s)}`)
      for (const s of t.secrets) md.push(`- secret \`${s.env}\` — get it at ${s.get}${s.note ? ` (${s.note})` : ""}`)
      if (t.verify) md.push(`- verify: \`${t.verify}\``)
      md.push("")
    }
  }
  await writeFile("catalog/TOOLCHAIN.md", md.join("\n"))

  const registries: Record<string, unknown> = {}
  for (const t of tools)
    for (const st of t.setup)
      if (st.kind === "registry") registries[st.namespace] = st.headers || st.params ? { url: st.url, headers: st.headers, params: st.params } : st.url
  for (const alias of config.legacyNamespaces) registries[alias] = `${SITE_URL}/r/{name}.json`
  await writeFile(
    "presets/components.registries.json",
    JSON.stringify(
      {
        $comment:
          "GENERATED from catalog/toolchain.json by scripts/build-toolchain.ts. The bootstrap (public/bootstrap.mjs) merges the registries of the tools it applies; this file is the full set for manual setup. Origin UI installs by URL (https://coss.com/origin/r/comp-N.json); shadcn blocks need no registry.",
        registries,
      },
      null,
      2
    ) + "\n"
  )

  const mcp = JSON.parse(await readFile(".mcp.json", "utf8")) as { mcpServers: Record<string, unknown> }
  mcp.mcpServers["design-infra"] = { type: "http", url: `${SITE_URL}/mcp` }
  await writeFile(".mcp.json", JSON.stringify(mcp, null, 2) + "\n")
  const plugin = JSON.parse(await readFile(".claude-plugin/plugin.json", "utf8")) as Record<string, unknown>
  plugin.repository = config.repositoryUrl
  await writeFile(".claude-plugin/plugin.json", JSON.stringify(plugin, null, 2) + "\n")

  execFileSync(
    "pnpm",
    ["exec", "esbuild", "scripts/bootstrap.ts", "--bundle", "--platform=node", "--format=esm", "--target=node20", "--outfile=public/bootstrap.mjs", "--banner:js=#!/usr/bin/env node"],
    { stdio: "inherit" }
  )
  console.log(`✓ toolchain: ${tools.length} tools → catalog/TOOLCHAIN.md, public/bootstrap.mjs`)
}

main()
