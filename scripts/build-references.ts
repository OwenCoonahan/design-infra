import { SITE_URL } from "../lib/config"
/**
 * catalog/references.json → catalog/REFERENCES.md ("where to look for X" + per-gallery etiquette).
 *
 *   pnpm references
 *
 * The routing table is produced by the same ranking agents get from MCP `find_references` / `/api/references`
 * (lib/catalog/references.ts), so the doc and the API never disagree. `pnpm check` fails when the file is stale.
 */
import { writeFileSync } from "node:fs"

import type { Mood } from "../lib/catalog/moods"
import { fill, loadReferences, referencesFor, type ReferenceHit, type ReferenceQuery, validateReferences } from "../lib/catalog/references"
import type { Category, Reference } from "../lib/catalog/schema"

/** Rows of the routing table — the patterns agents ask about most. */
export const ROUTES: { label: string; query: ReferenceQuery }[] = [
  { label: "navbar / header", query: { text: "navbar", category: "navigation" } },
  { label: "mega menu / dropdowns", query: { text: "mega menu dropdown navbar" } },
  { label: "mobile navigation", query: { text: "mobile navigation menu" } },
  { label: "footer", query: { text: "footer", category: "footer" } },
  { label: "hero", query: { text: "hero", category: "hero" } },
  { label: "features section", query: { text: "features section", category: "features" } },
  { label: "pricing page / section", query: { text: "pricing", category: "pricing" } },
  { label: "CTA / signup block", query: { text: "cta call to action", category: "cta" } },
  { label: "testimonials", query: { text: "testimonials", category: "testimonials" } },
  { label: "logo cloud", query: { text: "logo cloud customers", category: "logo-cloud" } },
  { label: "FAQ", query: { text: "faq", category: "faq" } },
  { label: "stats / metrics", query: { text: "stats metrics", category: "stats" } },
  { label: "animated landing page", query: { text: "animated landing page" } },
  { label: "scroll story / 3D / WebGL", query: { text: "scroll storytelling 3d webgl", category: "scroll-effect" } },
  { label: "hover / micro-interaction", query: { text: "hover interaction micro-interaction" } },
  { label: "minimal / refined look", query: { text: "minimal refined look", moods: ["minimal", "refined"] as Mood[] } },
  { label: "dark technical SaaS", query: { text: "dark saas dev tool", moods: ["technical"] as Mood[] } },
  { label: "trustworthy fintech / B2B", query: { text: "fintech b2b saas", moods: ["trustworthy"] as Mood[] } },
  { label: "editorial / typographic", query: { text: "editorial typography", moods: ["editorial"] as Mood[] } },
  { label: "empty state", query: { text: "empty state", category: "empty-state" } },
  { label: "component anatomy (tabs, combobox…)", query: { text: "tabs combobox component anatomy accessibility" } },
  { label: "mobile app flow (onboarding, checkout)", query: { text: "mobile app onboarding flow" } },
]

const cell = (h: ReferenceHit | undefined) =>
  h ? `[${h.name}${h.links[0] ? ` · ${h.links[0].label}` : ""}](${h.url})${h.access === "paid" ? " **(paid)**" : ""}` : "—"
const esc = (s: string) => s.replace(/\|/g, "\\|")

export function renderReferencesMd(refs: Reference[]) {
  const md: string[] = [
    "<!-- GENERATED by scripts/build-references.ts from catalog/references.json — edit the JSON, then `pnpm references` -->",
    "# References — where to look for ideas",
    "",
    "Inspiration **galleries** for one pattern at a time (navbars, footers, pricing, heroes, motion…). They are for",
    "*looking*, not installing: find an example that works, say what makes it work, then map it back to catalog",
    "components (`propose_options`, `search_components`). Free galleries first; paid ones are flagged.",
    "",
    "- MCP: `find_references` (pattern + optional category / moods) → ranked galleries with exact URLs + etiquette",
    `- HTTP: \`${SITE_URL}/api/references?pattern=<words>&category=<cat>&moods=<a,b>\``,
    "- Also attached as `references` (top 2) to `propose_options` and to every `plan_ui` section.",
    "",
    "## Where to look for X",
    "",
    "| looking for | first | second |",
    "|---|---|---|",
  ]
  for (const r of ROUTES) {
    const hits = referencesFor(r.query, refs)
    md.push(`| ${r.label} | ${cell(hits[0])} | ${cell(hits[1])} |`)
  }

  md.push(
    "",
    "## Galleries",
    "",
    "| gallery | best for | access | media | machine-readable |",
    "|---|---|---|---|---|",
    ...refs.map((r) => {
      const machine = Object.entries(r.machine)
        .filter(([k]) => k !== "toolchain")
        .map(([k, v]) => `[${k}](${v})`)
        .concat(r.machine.toolchain ? [`toolchain \`${r.machine.toolchain}\``] : [])
      return `| [${r.name}](${r.url}) | ${r.covers.slice(0, 5).join(", ")} | ${r.access} | ${r.media.join(", ")} | ${machine.join(" · ") || "—"} |`
    }),
    ""
  )

  for (const r of refs) {
    md.push(`### ${r.name}${r.access === "paid" ? " — PAID" : ""}`, "", `${r.summary} <${r.url}>`, "")
    md.push(`- **Moods:** ${r.moods.join(", ")} · **covers:** ${r.covers.join(", ")}`)
    for (const f of r.patterns) {
      if (f.values.length) md.push(`- **${f.label}:** \`${f.url}\` — ${f.values.map((v) => `[${v}](${fill(f.url, { value: v })})`).join(", ")}`)
      else md.push(`- **${f.label}:** <${f.url}>`)
    }
    if (r.item)
      md.push(
        `- **one entry:** \`${r.item.page}\` (e.g. <${fill(r.item.page, { slug: r.item.example })}>)${r.item.video ? ` · video \`${r.item.video}\`` : ""}`
      )
    md.push(`- **Attribution:** ${esc(r.etiquette.attribution)}`, `- **Crawling:** ${esc(r.etiquette.crawl)}`)
    if (r.etiquette.hotlinking) md.push(`- **Hotlinking:** ${esc(r.etiquette.hotlinking)}`)
    if (r.notes) md.push(`- **Notes:** ${esc(r.notes)}`)
    if (r.related.length) md.push(`- **Captured from here:** ${r.related.map((id) => `[${id}](../inspiration/${id.split("/")[1]}/README.md)`).join(", ")}`)
    md.push(`- _URL patterns verified ${r.verified}_`, "")
  }
  return md.join("\n")
}

function main() {
  const refs = loadReferences()
  const problems = validateReferences(refs)
  if (problems.length) {
    console.error(problems.map((p) => `✗ ${p}`).join("\n"))
    process.exit(1)
  }
  writeFileSync("catalog/REFERENCES.md", renderReferencesMd(refs))
  const cats = new Set<Category>(refs.flatMap((r) => r.covers))
  console.log(`✓ references: ${refs.length} galleries covering ${cats.size} categories → catalog/REFERENCES.md`)
}

if (/build-references\.ts$/.test(process.argv[1] ?? "")) main()
