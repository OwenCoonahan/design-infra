import { NAMESPACE } from "../lib/config"
/**
 * DESIGN.md → everything else.
 *
 *   pnpm tokens
 *
 * For every design-systems/<slug>/DESIGN.md (see design-systems/CONVENTIONS.md) this writes:
 *   design-systems/<slug>/theme.css        standalone CSS (paste into globals.css without the shadcn CLI)
 *   registry/oc/themes/registry.json       shadcn items: theme-<slug> + the font-* items it needs
 *   app/themes.generated.css               [data-theme] scoped vars for the gallery previews
 *   app/fonts.generated.ts                 next/font loaders for every font any system uses
 *   lib/design-systems.generated.json      metadata the gallery + skills read
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises"
import path from "node:path"

import { parse as parseYaml } from "yaml"

import { MOOD_NAMES, type Mood } from "../lib/catalog/moods"
import { MOTION_LANGUAGE_NAMES, MOTION_THEME_VARS, MOTION_TOKENS, motionCssVars, REDUCED_MOTION_CSS, type MotionLanguage } from "../lib/catalog/motion"

const ROOT = process.cwd()
const DS_DIR = path.join(ROOT, "design-systems")
const HEADER = "/* GENERATED by scripts/build-tokens.ts from design-systems/<slug>/DESIGN.md — do not edit. */\n"

const REQUIRED_COLORS = [
  "background",
  "foreground",
  "card",
  "card-foreground",
  "popover",
  "popover-foreground",
  "primary",
  "primary-foreground",
  "secondary",
  "secondary-foreground",
  "muted",
  "muted-foreground",
  "accent",
  "accent-foreground",
  "destructive",
  "border",
  "input",
  "ring",
] as const

/** shadcn variables that already have a Tailwind colour mapping in a stock shadcn globals.css. */
const SHADCN_COLORS = new Set<string>([
  ...REQUIRED_COLORS,
  "chart-1",
  "chart-2",
  "chart-3",
  "chart-4",
  "chart-5",
  "sidebar",
  "sidebar-foreground",
  "sidebar-primary",
  "sidebar-primary-foreground",
  "sidebar-accent",
  "sidebar-accent-foreground",
  "sidebar-border",
  "sidebar-ring",
])

const REQUIRED_TYPE = [
  "display",
  "headline-lg",
  "headline-md",
  "body-lg",
  "body-md",
  "body-sm",
  "label-md",
  "label-sm",
  "mono",
] as const

// Order matters: shadcn sets a `font-<role>` class on <html> for the last font item it installs,
// so sans must come last.
const FONT_ROLES = [
  ["mono", "mono"],
  ["heading", "headline-lg"],
  ["sans", "body-md"],
] as const

type Typo = {
  fontFamily: string
  fontSize: string
  fontWeight?: number | string
  lineHeight?: number | string
  letterSpacing?: string
}

type DesignTokens = {
  name: string
  moods?: string[]
  motion?: string
  description?: string
  colors: Record<string, string>
  typography: Record<string, Typo>
  rounded: Record<string, string>
  spacing?: Record<string, string | number>
}

type FontInfo = { import: string; variable: boolean; weight?: string[] }

export type DesignSystemMeta = {
  slug: string
  name: string
  description: string
  /** Feeling (lib/catalog/moods.ts), from the DESIGN.md `moods:` front-matter key. */
  moods: Mood[]
  /** Motion language (design-systems/MOTION.md), from the DESIGN.md `motion:` front-matter key. */
  motion: MotionLanguage
  fonts: { sans: string; heading: string; mono: string }
  radius: string
  /** Modes the gallery can preview; for single-mode systems, the scheme of its one palette. */
  modes: ("light" | "dark")[]
  light: Record<string, string>
  dark: Record<string, string>
  typography: Record<string, Typo>
  registryItem: string
}

/** Relative luminance of a #RGB/#RRGGBB colour; non-hex values count as light. */
function luminance(color: string) {
  const hex = /^#([\da-f]{6}|[\da-f]{3})(?:[\da-f]{2})?$/i.exec(color)?.[1]
  if (!hex) return 1
  const full = hex.length === 3 ? [...hex].map((c) => c + c).join("") : hex
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(full.slice(i, i + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")

function splitFrontMatter(src: string) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(src)
  if (!m) throw new Error("missing YAML front matter")
  return { data: parseYaml(m[1]) as DesignTokens, body: m[2] }
}

/** Resolve `{colors.x}` style references against the token tree. */
function resolveRef(value: string, tree: Record<string, unknown>, seen = new Set<string>()): string {
  const m = /^\{([^}]+)\}$/.exec(String(value).trim())
  if (!m) return String(value)
  if (seen.has(m[1])) throw new Error(`circular token reference ${m[1]}`)
  seen.add(m[1])
  const target = m[1].split(".").reduce<unknown>((o, k) => (o as Record<string, unknown>)?.[k], tree)
  if (typeof target !== "string") throw new Error(`unresolved token reference ${value}`)
  return resolveRef(target, tree, seen)
}

/** px → rem so the type scale respects user font-size settings. */
const toRem = (v: string) => {
  const m = /^(-?[\d.]+)px$/.exec(v)
  return m ? `${+(Number(m[1]) / 16).toFixed(4)}rem` : v
}

/** Text scale utilities (text-display…) + `font-headline` (weight of headline-lg; blocks use it instead of font-semibold so single-weight serifs aren't faux-bolded). */
function textScaleVars(typography: Record<string, Typo>) {
  const out: Record<string, string> = {
    "font-weight-headline": String(typography["headline-lg"].fontWeight ?? 600),
  }
  for (const level of REQUIRED_TYPE) {
    const t = typography[level]
    out[`text-${level}`] = toRem(t.fontSize)
    if (t.lineHeight !== undefined) out[`text-${level}--line-height`] = String(t.lineHeight)
    if (t.letterSpacing) out[`text-${level}--letter-spacing`] = t.letterSpacing
    if (t.fontWeight !== undefined) out[`text-${level}--font-weight`] = String(t.fontWeight)
  }
  return out
}

const block = (selector: string, vars: Record<string, string>, indent = "") =>
  `${indent}${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `${indent}  --${k}: ${v};`)
    .join("\n")}\n${indent}}\n`

async function main() {
  const { fonts: FONTS } = JSON.parse(await readFile(path.join(DS_DIR, "fonts.json"), "utf8")) as {
    fonts: Record<string, FontInfo>
  }

  const slugs = (await readdir(DS_DIR, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort()

  const systems: DesignSystemMeta[] = []
  const registryItems: Record<string, unknown>[] = []
  const fontItems = new Map<string, Record<string, unknown>>()
  const usedFamilies = new Set<string>()
  let galleryCss = HEADER
  const errors: string[] = []

  for (const slug of slugs) {
    const file = path.join(DS_DIR, slug, "DESIGN.md")
    let src: string
    try {
      src = await readFile(file, "utf8")
    } catch {
      continue
    }
    const fail = (msg: string) => errors.push(`${slug}: ${msg}`)
    const { data } = splitFrontMatter(src)
    const tree = data as unknown as Record<string, unknown>

    // ---- moods
    const moods = (data.moods ?? []) as Mood[]
    if (!moods.length) fail("missing `moods:` front-matter key (1-3 of: " + MOOD_NAMES.join(", ") + ")")
    for (const m of moods) if (!MOOD_NAMES.includes(m)) fail(`unknown mood "${m}" (use: ${MOOD_NAMES.join(", ")})`)

    const motion = data.motion as MotionLanguage
    if (!MOTION_LANGUAGE_NAMES.includes(motion))
      fail(`missing/unknown \`motion:\` front-matter key (one of: ${MOTION_LANGUAGE_NAMES.join(", ")} — see design-systems/MOTION.md)`)

    // ---- colors
    const colors = Object.fromEntries(
      Object.entries(data.colors ?? {}).map(([k, v]) => [k, resolveRef(String(v), tree)])
    )
    for (const c of REQUIRED_COLORS) if (!colors[c]) fail(`missing colors.${c}`)
    const light: Record<string, string> = {}
    const darkOverrides: Record<string, string> = {}
    for (const [k, v] of Object.entries(colors)) {
      if (k.startsWith("dark-")) darkOverrides[k.slice(5)] = v
      else light[k] = v
    }
    const hasDark = Object.keys(darkOverrides).length > 0
    const dark = { ...light, ...darkOverrides }
    for (const k of Object.keys(darkOverrides)) if (!(k in light)) fail(`dark-${k} has no default-mode counterpart`)
    const extraColors = Object.keys(light).filter((k) => !SHADCN_COLORS.has(k))

    // ---- typography
    const typography = data.typography ?? {}
    for (const t of REQUIRED_TYPE) if (!typography[t]) fail(`missing typography.${t}`)
    if (errors.length) continue
    const families = Object.fromEntries(FONT_ROLES.map(([role, level]) => [role, typography[level].fontFamily])) as {
      sans: string
      heading: string
      mono: string
    }
    for (const fam of Object.values(families)) {
      if (!FONTS[fam]) fail(`font "${fam}" is not in design-systems/fonts.json — add it (must be a Google Font)`)
      usedFamilies.add(fam)
    }

    // ---- radius
    const radius = data.rounded?.lg
    if (!radius) fail("missing rounded.lg")
    if (errors.length) continue

    const textVars = textScaleVars(typography)

    // ---- registry: font items (one per family+role, since the role decides the CSS variable)
    const fontDeps: string[] = []
    for (const [role, fam] of Object.entries(families)) {
      const info = FONTS[fam]
      const name = `font-${slugify(fam)}-${role}`
      fontDeps.push(`${NAMESPACE}/${name}`)
      if (!fontItems.has(name))
        fontItems.set(name, {
          name,
          type: "registry:font",
          title: `${fam} (${role})`,
          description: `${fam} from Google Fonts as --font-${role}.`,
          font: {
            family: fam,
            provider: "google",
            import: info.import,
            variable: `--font-${role}`,
            subsets: ["latin"],
            ...(info.variable ? {} : { weight: info.weight }),
          },
        })
    }

    // ---- registry: theme item
    const themeVars: Record<string, string> = { ...textVars }
    for (const c of extraColors) themeVars[`color-${c}`] = `var(--${c})`
    registryItems.push({
      name: `theme-${slug}`,
      type: "registry:theme",
      title: `${data.name} theme`,
      description: data.description ?? "",
      registryDependencies: fontDeps,
      cssVars: {
        theme: { ...themeVars, ...MOTION_THEME_VARS },
        light: { ...light, radius, ...motionCssVars(motion) },
        dark: { ...dark, radius, ...motionCssVars(motion) },
      },
      css: REDUCED_MOTION_CSS,
      files: [
        {
          path: `design-systems/${slug}/DESIGN.md`,
          type: "registry:file",
          target: "~/DESIGN.md",
        },
      ],
      docs: `${hasDark || luminance(light.background) >= 0.2 ? "" : 'Dark-only system: add className="dark" to <html>. '}Installed the ${data.name} theme. DESIGN.md was written to your project root — keep it there so agents follow it. Text scale utilities: ${REQUIRED_TYPE.map((t) => `text-${t}`).join(", ")}.`,
      categories: ["theme"],
      meta: { source: "oc", designSystem: slug },
    })

    // ---- standalone theme.css
    const standalone =
      `/* ${data.name} — generated from DESIGN.md by scripts/build-tokens.ts. Fonts: ${families.sans} / ${families.heading} / ${families.mono} (load via next/font as --font-sans / --font-heading / --font-mono). */\n\n` +
      block(":root", { ...light, radius, ...motionCssVars(motion) }) +
      "\n" +
      block(".dark", { ...dark, radius }) +
      "\n" +
      block("@theme inline", {
        ...Object.fromEntries(Object.keys(light).map((k) => [`color-${k}`, `var(--${k})`])),
        ...textVars,
        ...MOTION_THEME_VARS,
      }) +
      "\n@media (prefers-reduced-motion: reduce) {\n  :root { --motion-fast: 0ms; --motion-base: 120ms; --motion-slow: 150ms; }\n}\n"
    await writeFile(path.join(DS_DIR, slug, "theme.css"), standalone)

    // ---- gallery scoped CSS (explicit mode attribute; never depends on ancestors)
    const fontVars = Object.fromEntries(
      Object.entries(families).map(([role, fam]) => [`font-${role}`, `var(--font-g-${slugify(fam)})`])
    )
    const scoped = { ...fontVars, ...textVars, radius, ...motionCssVars(motion) }
    galleryCss += `\n/* ${data.name} */\n`
    galleryCss += block(`[data-theme="${slug}"]`, { ...light, ...scoped })
    galleryCss += block(`[data-theme="${slug}"][data-mode="dark"]`, dark)

    systems.push({
      slug,
      name: data.name,
      description: data.description ?? "",
      moods,
      motion,
      fonts: families,
      radius,
      modes: hasDark ? ["light", "dark"] : [luminance(light.background) < 0.2 ? "dark" : "light"],
      light,
      dark,
      typography,
      registryItem: `${NAMESPACE}/theme-${slug}`,
    })
  }

  if (errors.length) {
    console.error(errors.map((e) => `✗ ${e}`).join("\n"))
    process.exit(1)
  }

  // Gallery utilities need every text-* name declared once in @theme.
  const anyTheme = systems[0]
  if (anyTheme) {
    galleryCss += "\n@theme {\n"
    for (const [k, v] of Object.entries(textScaleVars(anyTheme.typography))) galleryCss += `  --${k}: ${v};\n`
    for (const [k, v] of Object.entries(MOTION_THEME_VARS)) galleryCss += `  --${k}: ${v};\n`
    galleryCss += "}\n"
  }

  await mkdir(path.join(ROOT, "registry/oc/themes"), { recursive: true })
  await writeFile(
    path.join(ROOT, "registry/oc/themes/registry.json"),
    JSON.stringify(
      {
        $schema: "https://ui.shadcn.com/schema/registry.json",
        items: [...registryItems, ...[...fontItems.values()].sort((a, b) => String(a.name).localeCompare(String(b.name)))],
      },
      null,
      2
    ) + "\n"
  )
  await writeFile(path.join(ROOT, "app/themes.generated.css"), galleryCss)

  // ---- @oc/motion-presets: the motion languages as motion/react transitions + variants
  await mkdir(path.join(ROOT, "registry/oc/lib/motion-presets"), { recursive: true })
  const presetsSrc = `/**
 * Motion presets for design-infra's motion languages (design-systems/MOTION.md).
 * GENERATED by design-infra scripts/build-tokens.ts from lib/catalog/motion.ts — installed via
 * \`npx shadcn@latest add ${NAMESPACE}/motion-presets\`. Set PROJECT_MOTION to the \`motion:\` value in ./DESIGN.md.
 *
 *   import { motionPreset } from "@/lib/motion-presets"
 *   const m = motionPreset()
 *   <motion.div variants={m.variants.fadeUp} initial="hidden" whileInView="show" viewport={{ once: true }} />
 *   <motion.button whileTap={m.press} transition={m.transition.fast} />
 *   <MotionConfig reducedMotion="user" transition={m.transition.base}>…</MotionConfig>
 */
import type { Transition, Variants } from "motion/react"

export type MotionLanguage = ${MOTION_LANGUAGE_NAMES.map((n) => JSON.stringify(n)).join(" | ")}

/** Change to match ./DESIGN.md \`motion:\` so every hand-written animation shares one language. */
export const PROJECT_MOTION: MotionLanguage = "quiet"

export const MOTION_TOKENS = ${JSON.stringify(MOTION_TOKENS, null, 2)} as const

export function motionPreset(lang: MotionLanguage = PROJECT_MOTION) {
  const t = MOTION_TOKENS[lang]
  const tween = (ms: number, ease: readonly number[]): Transition => ({ duration: ms / 1000, ease: [...ease] as [number, number, number, number] })
  const transition = {
    fast: tween(t.fast, t.easeOut),
    base: tween(t.base, t.easeOut),
    slow: tween(t.slow, t.easeOut),
    exit: tween(t.base * 0.75, t.easeIn),
    move: tween(t.base, t.easeInOut),
    spring: { ...t.spring } as Transition,
  }
  const variants = {
    fadeIn: { hidden: { opacity: 0 }, show: { opacity: 1, transition: transition.base } },
    fadeUp: {
      hidden: { opacity: 0, y: t.travel },
      show: { opacity: 1, y: 0, transition: transition.slow },
    },
    scaleIn: {
      hidden: { opacity: 0, scale: t.scaleFrom },
      show: { opacity: 1, scale: 1, transition: lang === "lively" ? transition.spring : transition.base },
      exit: { opacity: 0, scale: t.scaleFrom, transition: transition.exit },
    },
    /** Parent of a list: children use fadeUp / fadeIn. */
    stagger: { hidden: {}, show: { transition: { staggerChildren: t.stagger } } },
  } satisfies Record<string, Variants>
  return {
    lang,
    tokens: t,
    transition,
    variants,
    /** whileTap target for buttons/cards. */
    press: { scale: lang === "still" ? 1 : 0.97 },
    /** whileHover lift for cards (none in still). */
    lift: { y: lang === "still" ? 0 : -Math.max(1, Math.round(t.travel / 3)) },
  }
}
`
  await writeFile(path.join(ROOT, "registry/oc/lib/motion-presets/motion-presets.ts"), presetsSrc)
  await writeFile(
    path.join(ROOT, "registry/oc/lib/registry.json"),
    JSON.stringify(
      {
        $schema: "https://ui.shadcn.com/schema/registry.json",
        items: [
          {
            name: "motion-presets",
            type: "registry:lib",
            title: "Motion presets",
            description:
              "design-infra's motion languages (still / quiet / lively / cinematic) as motion/react transitions, springs and variants (fadeUp, scaleIn, stagger, press, lift). Set PROJECT_MOTION to your DESIGN.md `motion:` so hand-written animations match the system.",
            dependencies: ["motion"],
            files: [{ path: "registry/oc/lib/motion-presets/motion-presets.ts", type: "registry:lib", target: "lib/motion-presets.ts" }],
            categories: ["transition"],
            meta: { source: "oc", moods: ["refined"] },
          },
        ],
      },
      null,
      2
    ) + "\n"
  )

  const families = [...usedFamilies].sort()
  const ident = (fam: string) => slugify(fam).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
  const imports = [...new Set(families.map((f) => FONTS[f].import))].sort()
  let fontsTs = `// GENERATED by scripts/build-tokens.ts — do not edit.\nimport { ${imports.join(", ")} } from "next/font/google"\n\n`
  for (const fam of families) {
    const info = FONTS[fam]
    const weight = info.variable ? "" : `, weight: ${JSON.stringify(info.weight)}`
    fontsTs += `const ${ident(fam)} = ${info.import}({ subsets: ["latin"], variable: "--font-g-${slugify(fam)}", display: "swap"${weight} })\n`
  }
  fontsTs += `\n/** className that defines every --font-g-* variable used by the design-system previews. */\nexport const designSystemFontVariables = [${families
    .map((f) => `${ident(f)}.variable`)
    .join(", ")}].join(" ")\n`
  await writeFile(path.join(ROOT, "app/fonts.generated.ts"), fontsTs)

  await writeFile(path.join(ROOT, "lib/design-systems.generated.json"), JSON.stringify(systems, null, 2) + "\n")

  const readme = [
    "<!-- GENERATED by scripts/build-tokens.ts — edit the DESIGN.md files, then pnpm tokens. -->",
    "# Design systems",
    "",
    "Each folder holds one `DESIGN.md` ([Google DESIGN.md format](https://github.com/google-labs-code/design.md) + our",
    "[conventions](./CONVENTIONS.md)) and the generated `theme.css`. Install one into a project with",
    `\`pnpm dlx shadcn@latest add ${NAMESPACE}/theme-<slug>\` — tokens, fonts, text scale, and DESIGN.md at the project root.`,
    "",
    "| slug | name | moods | motion | best for | headings · body · mono | radius | modes | install |",
    "|---|---|---|---|---|---|---|---|---|",
    ...systems.map(
      (s) =>
        `| [${s.slug}](./${s.slug}/DESIGN.md) | ${s.name} | ${s.moods.join(", ")} | [${s.motion}](./MOTION.md#${s.motion}) | ${s.description.replace(/\|/g, "\\|")} | ${s.fonts.heading} · ${s.fonts.sans} · ${s.fonts.mono} | ${s.radius} | ${s.modes.join(" + ")} | \`${s.registryItem}\` |`
    ),
    "",
    "## Adding one",
    "",
    "1. Copy the closest folder to `design-systems/<slug>/` and rewrite DESIGN.md (keep the required token names).",
    "2. New font? Add it to `fonts.json` (Google Fonts only).",
    "3. `pnpm generate && pnpm check` — lints, regenerates theme.css, the registry item, the gallery preview and this table.",
    "",
  ].join("\n")
  await writeFile(path.join(DS_DIR, "README.md"), readme)

  console.log(`✓ ${systems.length} design systems → ${registryItems.length} themes, ${fontItems.size} font items`)
}

main()
